import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {stripTypeScriptTypes} from 'node:module';
const root=new URL('../',import.meta.url);
const paths=['utils/softContact.ts','utils/odangoFur.ts','utils/evolved3d.ts','assets/images/characters/bone/odango/body.webp'];
const inputs=paths.map(p=>readFileSync(new URL(p,root)));
const hash=createHash('sha256').update(Buffer.concat(inputs)).digest('hex');
const target=new URL('utils/nativeResidentBundle.ts',root);
if(process.argv.includes('--check')){
 if(!readFileSync(target,'utf8').includes(`source-sha256: ${hash}`))throw Error('Native resident is out of date. Run node scripts/build-native-resident.mjs');
 console.log('Native resident matches the web renderer and original coat.');
}else{
 const js=inputs.slice(0,3).map(b=>stripTypeScriptTypes(b.toString(),{mode:'strip'}).replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,''));
 const source=`const contact=(()=>{${js[0]}\nreturn {softContactHeight,softContactSpread};})();\nconst coat=(()=>{${js[1]}\nreturn {createOdangoCoat};})();\nconst evolved=(()=>{const {softContactHeight,softContactSpread}=contact;const {createOdangoCoat}=coat;${js[2]}\nreturn {createEvolvedRenderer};})();`;
 const content=`// Generated by scripts/build-native-resident.mjs. Do not edit.\n// source-sha256: ${hash}\nexport const NATIVE_RESIDENT_SCRIPT=${JSON.stringify(source)};\nexport const NATIVE_ODANGO_COAT=${JSON.stringify('data:image/webp;base64,'+inputs[3].toString('base64'))};\n`;
 writeFileSync(target,content);console.log('Bundled the shared web renderer and original coat for offline native use.');
}
