    assert.ok(energyKey);
    const energy=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),energyKey);
    assert.equal(energy.flags.mood,true);
    await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
    await page.getByTestId('light-flow-feedback').waitFor({state:'hidden'});
    await page.waitForTimeout(5000);
    await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
    await page.getByTestId('light-flow-feedback').waitFor({state:'visible'});
