    await page.getByTestId('energy-garden').waitFor({state:'visible'});
    console.log('PASS saved record feedback, static mode, hidden-tab pause, garden link');
    await page.getByText('部屋',{exact:true}).last().click();
    await page.getByTestId('room-record').click();
